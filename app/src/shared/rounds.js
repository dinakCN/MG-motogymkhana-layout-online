// Момент дня. Определяет, что написано на сцене «Пауза»: перерыв —
// плановый элемент вещания, поэтому в кадре всегда сказано, что будет
// дальше, а не просто «пауза».
//
// Тексты живут здесь, а не в сцене: пульт показывает оператору ровно то,
// что уйдёт в кадр. Разъехавшиеся копии означали бы, что оператор
// переключает раунд вслепую.
// Времени в подписях нет намеренно. Часы в кадре обязывают, а программа
// соревнований сдвигается всегда: «Вторая серия заездов в 14:30» становится
// враньём раньше, чем кто-нибудь это заметит, и поправить его посреди эфира
// будет некому. Обещание продолжения при этом остаётся — оно и держит
// зрителя, а не названная минута.
export const ROUNDS = [
  { key: 'round1', label: '1-я серия', title: 'Идут заезды', sub: 'Первая серия' },
  { key: 'break1', label: 'Перерыв', title: 'Перерыв', sub: 'Скоро вторая серия заездов' },
  { key: 'round2', label: '2-я серия', title: 'Идут заезды', sub: 'Вторая серия' },
  { key: 'final', label: 'Итоги', title: 'Подведение итогов', sub: 'Скоро награждение' },
  { key: 'break2', label: 'Перед награждением', title: 'Готовимся к награждению', sub: '' },
  { key: 'awards', label: 'Награждение', title: 'Награждение', sub: '' },
]

export function roundText(key) {
  return ROUNDS.find(r => r.key === key) ?? ROUNDS[0]
}
