import { bestOf } from './format.js'

// ────────────────────────────────────────────────────────────────────────
// Явка. Часть заявленных не приезжает на этап, и узнать об этом можно
// только на площадке: с сайта неявка не приходит вовсе — у неприехавшего
// просто нет прокатов, ровно как у того, кто ещё не стартовал.
//
// Отметку ставит оператор до начала заездов, хранится она в состоянии
// сервера (state.riderStatus) рядом с ручными группами и по той же причине:
// participants перезаписываются целиком каждые семь секунд.
// ────────────────────────────────────────────────────────────────────────

// Did Not Start — единственное значение статуса сегодня. Строкой, а не
// булевым флагом: «снят с соревнований» и «дисквалифицирован» — соседние
// состояния, и поле примет их без смены формата, когда они понадобятся.
export const DNS = 'dns'

// Ехал ли человек вообще. bestOf возвращает null ровно тогда, когда ни одной
// попытки с временем не записано; «сход» и «незачёт» — это следы заезда,
// а значит человек стоял на старте.
const hasRidden = rider => bestOf(rider) !== null

// Отметка — предположение оператора, сделанное утром; протокол — факт.
// Поэтому любой след заезда отменяет отметку, и отменяет молча: человек,
// который реально проехал, обязан вернуться в кадр сам. О противоречии
// пульт скажет отдельно (noShowConflicts) — чинить его должен оператор.
export function isNoShow(rider, riderStatus = {}) {
  return riderStatus?.[rider?.id] === DNS && !hasRidden(rider)
}

// Те, кто реально соревнуется. Единственный фильтр на всю графику: сцены
// получают состав уже просеянным (OverlayRoot), иначе таблица, топ-3 и подиум
// разошлись бы при первой же правке — а расхождение таблицы с подиумом в день
// награждения хуже любой другой поломки.
export function competing(participants = [], riderStatus = {}) {
  return participants.filter(rider => !isNoShow(rider, riderStatus))
}

// Отмеченные, у которых всё-таки есть результат. Состояние не чинится само:
// отметку снимает оператор, а до тех пор человек едет в кадре как обычно.
export function noShowConflicts(participants = [], riderStatus = {}) {
  return participants.filter(
    rider => riderStatus?.[rider?.id] === DNS && hasRidden(rider),
  )
}

// Счётчики шапки списка. Считаются в одном месте с фильтром: «едут 19»
// в пульте и число строк в кадре обязаны сходиться.
export function countsOf(participants = [], riderStatus = {}) {
  let noShow = 0
  let conflicts = 0

  for (const rider of participants) {
    if (riderStatus?.[rider?.id] !== DNS) continue
    if (hasRidden(rider)) conflicts += 1
    else noShow += 1
  }

  return {
    declared: participants.length,
    competing: participants.length - noShow,
    noShow,
    conflicts,
  }
}
